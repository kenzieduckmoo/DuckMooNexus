const assert=require('node:assert/strict');
const {completionSnapshot,dailyCandidates,evaluateDailyPlan}=require('./daily-plan.js');
const {evaluateBatch}=require('./batch-evaluation.js');
const now=1200;
const recipe=name=>({key:'c:2:q2:'+name,scope:'Alliance - One',name:'Potion',profession:'Alchemy',materials:{'i:1':2},quantity:1,output:'i:9',crafters:[{guid:name,name,realm:'One'}],capture:{observedAt:900,concentration:100,skillLineID:1}});
const snapshot={recipes:['A','B'].map(recipe),characters:['A','B'].map(name=>({guid:name,name,realm:'One',professions:[{id:1,name:'Midnight Alchemy',concentration:{amount:500,max:500,observedAt:900,secondsPerPoint:100}}]})),catalog:['A','B'].map(guid=>({guid,recipeID:2,learned:true,observedAt:900,cooldownCaptured:true,cooldown:{seconds:0,observedAt:900}})),inventory:{items:{'i:1':[{owner:'Warband',location:'warband',bound:true,quantity:20,observedAt:900}]}},sources:[{name:'Syndicator',savedAt:900}],market:{commodities:{'i:1':{price:1},'i:9':{price:100}}}};
const entries=dailyCandidates(snapshot,[],5,now),a=entries.find(e=>e.setup.crafterName==='A'),b=entries.find(e=>e.setup.crafterName==='B');
const completed=[{...a.setup,count:2,completedAt:1000}];
let effective=completionSnapshot(snapshot,completed,now);
assert.equal(effective.characters[0].professions[0].concentration.amount,300);
assert.equal(effective.characters[1].professions[0].concentration.amount,500);
assert.equal(effective.inventory.items['i:1'][0].quantity,16);
assert.equal(snapshot.inventory.items['i:1'][0].quantity,20);
assert.equal(snapshot.characters[0].professions[0].concentration.amount,500);
assert.equal(evaluateBatch(effective,b,5,[],now).feasible,true);
assert.equal(evaluateBatch(effective,a,4,[],now).feasible,false);
const stale={...a.setup,id:'old',recipeKey:'c:99:q2:missing',count:1};
const plan=evaluateDailyPlan(effective,[stale],now);
assert.match(plan.lines[0].result.error,/missing/);
assert.equal(plan.pools[0].required,100);
assert.equal(plan.shopping[0].used,2);
assert.equal(evaluateBatch(effective,b,5,[stale],now).feasible,true);
assert.equal(evaluateBatch(effective,a,3,[stale],now).feasible,false);
// Fresh observations replace provisional debits, without subtracting twice.
snapshot.characters[0].professions[0].concentration={amount:300,max:500,observedAt:1200,secondsPerPoint:100};
snapshot.inventory.items['i:1'][0]={owner:'Warband',location:'warband',bound:true,quantity:16,observedAt:1100};
snapshot.sources[0].savedAt=1100;
effective=completionSnapshot(snapshot,completed,now);
assert.equal(effective.characters[0].professions[0].concentration.amount,300);
assert.equal(effective.inventory.items['i:1'][0].quantity,16);
assert.equal(effective.pendingCompleted.length,0);
const {evaluateSetup}=require('./profit-ui.js');
snapshot.recipes[0].capture.observedAt=1100;
assert.equal(evaluateSetup(snapshot,a.setup,now).error,undefined);
snapshot.recipes[0].capture.concentration=200;
assert.match(evaluateSetup(snapshot,a.setup,now).error,/changed when recaptured/);
console.log('Crafting continuity: independent characters, pending resource and stock debits, stale-line reservations, fresh-observation replacement passed.');
