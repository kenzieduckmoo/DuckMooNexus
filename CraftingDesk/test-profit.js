const assert=require('node:assert/strict');
const {financialEstimate,concentrationBudget,evaluateSetup,concentrationGain,setupFromCapture}=require('./profit-ui.js');
const estimate=financialEstimate(200000,2,10,15000,5,100);
assert.equal(estimate.net,285000);
assert.equal(estimate.profit,85000);
assert.equal(estimate.goldPerPoint,85);
assert.equal(financialEstimate(null,2,1,100,5,0).profit,null);
assert.equal(financialEstimate(10,2,1,null,5,0).profit,null);
assert.equal(financialEstimate(10,2,1,0,5,0).profit,-10);
const record={amount:100,max:1000,observedAt:1000,secondsPerPoint:10};
assert.equal(concentrationBudget(record,100,2,1500).available,150);
assert.equal(concentrationBudget(record,100,2,1500).wait,500);
assert.equal(concentrationBudget(record,100,11,1500).overCap,true);
assert.equal(concentrationBudget(record,100,2,0).available,100);
assert.equal(concentrationBudget(record,100,2,50000).available,1000);
assert.equal(concentrationBudget(null,100,2),null);
assert.equal(concentrationBudget({...record,secondsPerPoint:0},100,2),null);
assert.equal(concentrationBudget(null,0,2).wait,0);
const recipe={key:'c:1:q1',scope:'Alliance - A',materials:{'i:1':2},crafters:[{name:'A',realm:'A',guid:'one'}]};
const setup={recipeKey:recipe.key,scope:recipe.scope,crafterName:'A',realm:'A',materialSignature:JSON.stringify(Object.entries(recipe.materials).sort()),selections:{'i:1':'i:1'},count:1,output:'i:2',quantity:1,fee:5,concentration:0};
const snapshot={recipes:[recipe],market:{commodities:{'i:1':{price:100},'i:2':{price:300}}}};
assert.equal(evaluateSetup(snapshot,setup).finance.profit,85);
assert.equal(evaluateSetup(snapshot,{...setup,salePrice:0}).finance.profit,-200);
assert.ok(evaluateSetup(snapshot,{...setup,materialSignature:'changed'}).error);
assert.ok(evaluateSetup({},setup).error);
const base={setup:{...setup,name:'Baseline'},result:{finance:{perCraft:100}}};
const con={setup:{...setup,concentration:20},result:{finance:{perCraft:300}}};
assert.equal(concentrationGain(con,[base,con]).perPoint,10);
assert.equal(concentrationGain(con,[]),null);
assert.equal(concentrationGain(con,[{...base,setup:{...base.setup,crafterName:'Other'}}]),null);
const captured={...recipe,output:'i:2',quantity:1,name:'Captured',capture:{observedAt:1000,concentration:100,skillLineID:1,manualSalePrice:false}};
const capturedSetup=setupFromCapture(captured);
const capturedData={...snapshot,recipes:[captured]};
assert.equal(evaluateSetup(capturedData,capturedSetup).finance.profit,85);
assert.ok(evaluateSetup(capturedData,{...capturedSetup,capturedAt:999}).error);
captured.capture.manualSalePrice=true;
assert.equal(evaluateSetup(capturedData,capturedSetup).finance.profit,null);
console.log('Profit, missing-data, repricing, and concentration checks passed');
